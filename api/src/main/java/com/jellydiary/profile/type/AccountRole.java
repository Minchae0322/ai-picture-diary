package com.jellydiary.profile.type;

/**
 * 계정의 권한. **프로필이 사용자 테이블을 겸하므로 권한도 여기 있다**(ADR 2026-10-20).
 *
 * <p>기기로만 식별되는 사람과 계정을 가진 사람을 가른다. 이 구분을 {@code tb_guest_device} 의 존재 여부로 하면 <b>로그인한 뒤에도 그 행이 남아
 * 영원히 게스트로 판정된다</b> - 사용자 번호가 바뀌지 않는 설계이기 때문이다. 권한을 계정 쪽에 두면 승격이 필드 하나를 바꾸는 일이 된다.
 */
public enum AccountRole {
    /** 기기로만 식별된다. 핵심 루프(02~06)는 열려 있고 07·08·09·10 은 막힌다 */
    GUEST,
    /** 계정이 있다. **아직 이 값이 되는 길이 없다** - 인증이 붙으면 Profile.promote() 가 그 자리다 */
    MEMBER
}
